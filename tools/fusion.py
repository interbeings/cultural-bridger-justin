# 23 이차함수 + 행렬 아닌, 연립 + 집합: 공통근 + 집합 원소 개수
def c23():
    cnt = 0
    for k in range(-20, 21):
        A = {round(r.real, 9) for r in np.roots([1, k, 6]) if abs(r.imag) < 1e-9}
        B = {round(r.real, 9) for r in np.roots([1, -5, 6])}
        if len(A & B) == 1: cnt += 1
    return str(cnt)
