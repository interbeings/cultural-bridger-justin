def saryo_items(rng):
    out = []
    for cat, ref, name, src, facts in SARYO:
        pool = [(n, f) for c, _, n, _, fs in SARYO if c in POOL[cat] and n != name for f in fs]
        for t in facts:
            ds = rng.sample(pool, 4)
            if len({n for n, _ in ds}) < 4:
                ds = rng.sample(pool, 4)
            opts = [t] + [f for _, f in ds]
            rng.shuffle(opts)
            q = rng.choice(QWORD[cat])
            if cat == '단체' and q.startswith("다음 자료의 '이") and '이 단체' not in src:
                q = QWORD['단체'][0]
            if cat == '단체' and src.startswith('이 정부'):
                q = '다음 자료에 나타난 정부에 대한 설명으로 옳은 것은?'
            if cat == '인물' and not src.startswith('그'):
                q = '다음 자료에 나타난 인물에 대한 설명으로 옳은 것은?'
            if name == '흥선 대원군':
                q = "다음 자료의 '그'가 추진한 정책으로 옳은 것은?"
            p = src
            exp = f'자료의 대상은 {name}입니다. 정답: {t} / 오답 선지는 ' + ', '.join(f'{n}' for n, _ in ds) + '에 해당합니다.'
            out.append(dict(u='한국사', l=3 if cat in ('왕', '운동') else 4, s='사료 제시형', q=q, p=p, o=opts, a=opts.index(t), x=exp, sh=1))
    return out


def comparative(it):
    m = re.match(r'갑국과 을국은 X재와 Y재만 생산한다\. 1단위 생산에 필요한 노동 시간이 갑국은 X재 (\d+)시간·Y재 (\d+)시간, 을국은 X재 (\d+)시간·Y재 (\d+)시간이다\. (.*)$', it['q'], re.S)
    if not m:
        return False
    a, b, c, d, rest = m.groups()
    it['f'] = table(['구분', 'X재', 'Y재'], [['갑국', a, b], ['을국', c, d]], '재화 1단위 생산에 필요한 노동 시간(시간)')
    rest = rest.replace('(비교 우위에 따라 특화·교역)', '').strip()
    it['q'] = '표는 X재와 Y재만 생산하는 갑국과 을국에서 각 재화 1단위를 생산하는 데 필요한 노동 시간을 나타낸 것이다. 이에 대한 설명으로 ' + (rest if rest else '옳은 것은?') + '\n(단, 두 나라는 비교 우위가 있는 재화 생산에 특화하여 교역하며, 생산 요소는 노동뿐이다.)'
    it['q'] = it['q'].replace('설명으로 옳은 것은?', '설명으로 옳은 것은?')
    it['s'] = '자료 해석형'
    return True


def apply(items, replace_units, rng):
    conv = sum(comparative(it) for it in items if it['u'] == '시장경제')
    new = saryo_items(rng)
    cand = [it['id'] for it in items if it['u'] == '한국사' and it['q'].startswith('다음 사건을 일어난 순서대로')]
    rng.shuffle(cand)
    n = min(len(new), len(cand) - 40)
    drop = set(cand[:n])
    rng.shuffle(new)
    new = new[:n]
    for i, it in enumerate(new):
        it['id'] = f'PH{i + 1:03d}'
    print(f'  사회: 비교 우위 표 제시형 {conv}, 한국사 사료 제시형 {n}')
    return [it for it in items if it['id'] not in drop] + new
